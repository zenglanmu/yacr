// The `dom-canvas` transport (ADR 0024 D1/D3): the wasm CAD session owns the
// pixels **and** the camera, and this module owns the narrow seam between that
// session and the one input element the chrome already has.
//
// What this module does, and what it deliberately does not:
//
// * it **loads** the generated wasm session and waits for its init;
// * it **sizes** the session (`start` once, `resize` on a real size/DPR change)
//   from the partition rect the chrome measures;
// * it reports the session's own status and its first failure, once.
//
// It does **not** synthesize input. Pan, zoom, hover and every tool click travel
// the shared lane (`cad/input.ts` → `probe_input` → the adapter), which is the
// same code path the `native-below` hosts use, so a wheel notch or a middle-drag
// means exactly the same thing on the page carrier as on the desktop. That is why
// there is no second camera owner here any more: the session's own input seam
// already owns it, and a second "zoom the camera from the transport" path could
// only disagree with the first.
//
// How the session is loaded, and why it goes through a **public bootstrap module**:
//
// * the artifacts are generated by `scripts/build-canvas-wasm.sh` (`app_web.js` +
//   one `app_web_bg.wasm` + a three-line `bootstrap.js`) and served from the
//   frontend dist root at `/canvas/`. They are not source files of this package and
//   not part of this bundle's asset graph;
// * a dynamic `import()` of that URL from **inside the bundle** does not survive
//   Vite 8's dev transform: it becomes
//   `import(__vite__injectQuery(url, 'import'))`, i.e. it requests
//   `/canvas/app_web.js?import`, which the dev server answers **HTTP 500** with its
//   error-overlay HTML for a public-dir file (`/* @vite-ignore */` does not stop the
//   query injection). Observed on the X11 host as WebKit's opaque
//   `TypeError: Importing a module script failed.` while a plain `fetch` of the very
//   same URL returned `200 text/javascript` — which is why the failure probe below
//   records origin/href/status/content-type;
// * so the import graph starts **outside** the bundler: this loader injects
//   `<script type="module" src="/canvas/bootstrap.js">`. Files under `public/` are
//   served verbatim by the dev server and copied verbatim into `dist/`, so nothing
//   rewrites the bootstrap's own `import` statements. The bootstrap imports the
//   session, starts initialisation with the explicit `app_web_bg.wasm` URL, and
//   publishes `{ ready, ...module }` on `globalThis.__YACR_CANVAS_MODULE__`;
// * a `--target no-modules` classic script is **not** usable: its glue reads
//   `document.currentScript.src` behind a `document.currentScript !== null` guard,
//   and WebKitGTK leaves `document.currentScript` **`undefined`** while a
//   dynamically inserted classic script runs. `undefined !== null` is true, the
//   top-level `let wasm_bindgen` never initialises, and every later
//   `typeof wasm_bindgen` throws
//   `ReferenceError: Cannot access 'wasm_bindgen' before initialization.` (verified
//   in WebKitGTK 2.52.6, independent of Tauri). No bare-global handling remains;
// * `eval`/`new Function` are not options either: the host CSP has no
//   `'unsafe-eval'`.
//
// `native-below` hosts (Linux native Wayland, Windows) never load any of this: the
// loader is only reachable from the `dom-canvas` branch in `App.tsx`. The host
// shell must also allow WebAssembly instantiation in its CSP (`'wasm-unsafe-eval'`
// under `script-src`); that file belongs to the host lane, and a CSP refusal
// surfaces as this transport's load failure - never as a blank canvas.
//
// Everything that can be a pure function is one (`canvasCssSize`,
// `parseCanvasStatus`, `statusFailure`); the one DOM binding at the bottom only
// measures, coalesced to one animation frame. The canvas node is a pixel surface:
// no listener is ever attached to it here (ADR 0024 D3).
//
// The generated session is **not** a source dependency of this package, so its
// module namespace arrives as `unknown` and is narrowed here: the exports this
// transport calls are checked before the object is used.
import { rectFromElement } from './metrics.ts';

/** The single canvas the wasm session presents on (ADR 0024 D3). */
export const CANVAS_ID = 'cad-canvas';

/** The dist-root directory both generated artifact sets are served from. */
export const CANVAS_BASE = '/canvas/';

/** The wasm-bindgen ES module: the session itself (also used by `apps/app-web/web`). */
export const CANVAS_MODULE_FILE = 'app_web.js';

/**
 * The bootstrap **module** this loader injects.
 *
 * Generated into `public/canvas/` by `scripts/build-canvas-wasm.sh`; because it
 * lives under `public/`, neither the dev server nor the bundler rewrites its
 * imports (see the file header).
 */
export const CANVAS_BOOTSTRAP_FILE = 'bootstrap.js';

/** The one wasm binary the bootstrap initialises from. */
export const CANVAS_WASM_FILE = 'app_web_bg.wasm';

/** The global the bootstrap publishes `{ ready, ...module }` on. */
export const CANVAS_GLOBAL = '__YACR_CANVAS_MODULE__';

declare global {
  /** The `{ ready, ...module }` object the canvas bootstrap publishes. */
  var __YACR_CANVAS_MODULE__: unknown;
}

/**
 * Failure steps **this module** classifies, for the cases where the wasm session
 * never got far enough to report one of its own.
 *
 * Deliberately *not* reusing the wasm status vocabulary: `webgl2`, `surface`,
 * `import`, ... are the session's words, and a host maps them to its own refusal
 * (`webgl2` -> stable marker `yacr: unsupported-runtime: webgl2`, exit code 6).
 * These three names describe failures that happen outside the session, and the
 * `-` prefix keeps them from ever colliding with a session step.
 */
export const CANVAS_STEP_MODULE = 'ui-module-load';
export const CANVAS_STEP_CALL = 'ui-export-threw';
export const CANVAS_STEP_UNREADABLE = 'ui-status-unreadable';

/** A failure status that carries no step of its own. */
export const CANVAS_STEP_UNCLASSIFIED = 'unclassified';

/**
 * The exports every wasm session module must provide for this transport.
 *
 * `frame` is here because the page carrier's loop is the **host's** (see
 * `cad/frame-loop.ts`): nothing inside wasm starts a timer, so a session whose
 * frame step cannot be called could never repaint and must be refused at load
 * time rather than after a blank canvas.
 */
export const CANVAS_EXPORTS = ['start', 'resize', 'frame'];

/**
 * The session's call surface, after validation. Every call answers with the
 * session's own status JSON (a string); a rejection is a transport failure.
 *
 * `frame()` answers a *frame* line (`{ok, presented, frames, waited, ticks,
 * canvasFrames}`), not a status: it is driven by `cad/frame-loop.ts` and is not a
 * status source here.
 */
export interface CanvasModule {
  readonly ready?: unknown;
  start(canvasId: string, width: number, height: number, dpr: number): unknown;
  resize(width: number, height: number, dpr: number): unknown;
  frame(): unknown;
}

/** The page global the loader runs against (`globalThis` in a host). */
export interface CanvasEnv {
  readonly document?: Document;
  readonly location?: { readonly origin?: string; readonly href?: string };
  readonly fetch?: typeof fetch;
  readonly __YACR_CANVAS_MODULE__?: unknown;
}

/** One classified failure: everything the host needs for its refusal line. */
export interface CanvasFailure {
  /** The session's step, or one of this module's `ui-*` steps. */
  readonly step: string;
  /** The session's own `error`, or the raw status text. Never invented copy. */
  readonly detail: string;
  /** The stable marker the status carried (`yacr: unsupported-runtime: …`). */
  readonly marker: string | null;
  /** Which export the call failed on, when the failure came from a call. */
  readonly at?: string;
}

/** A partition size, in CSS px plus the device pixel ratio. */
export interface CanvasCssSize {
  readonly width: number;
  readonly height: number;
  readonly dpr: number;
}

/**
 * The served directory both artifact sets live in.
 *
 * Accepts a directory (`/canvas/`, `/canvas`, an absolute URL ending in a slash)
 * or a URL naming one of the files themselves (`…/bootstrap.js`), so a
 * caller may pass either what it configured or what it resolved. Anything else is
 * not a base: the default is used rather than a broken specifier.
 */
export function canvasBaseDir(base: unknown = CANVAS_BASE): string {
  const value = typeof base === 'string' && base.length > 0 ? base : CANVAS_BASE;
  if (value.endsWith('/')) return value;
  // A trailing file name is dropped; a bare directory gets its slash.
  return /\.[a-z0-9]+$/i.test(value) ? value.slice(0, value.lastIndexOf('/') + 1) : `${value}/`;
}

/** The bootstrap-module URL this loader injects. */
export function canvasScriptUrl(base: unknown = CANVAS_BASE): string {
  return `${canvasBaseDir(base)}${CANVAS_BOOTSTRAP_FILE}`;
}

/** The wasm binary the bootstrap names explicitly (also used in failure text). */
export function canvasWasmUrl(base: unknown = CANVAS_BASE): string {
  return `${canvasBaseDir(base)}${CANVAS_WASM_FILE}`;
}

/** The bootstrap URL, by its historical name (`App.tsx` passes it to the loader). */
export function canvasModuleUrl(base: unknown = CANVAS_BASE): string {
  return canvasScriptUrl(base);
}

/**
 * Diagnostic suffix for a failed load: page origin/href plus the plain-`fetch`
 * outcome for the same URL.
 *
 * Kept from the first version of this loader, where it turned an opaque WebKit
 * "Importing a module script failed." into
 * `[origin=… href=… fetch=200 text/javascript]` — the evidence that identified
 * the Vite `?import` rewrite as the cause. A script `error` event is just as
 * opaque, so the same probe is attached to it.
 */
async function assetProbe(env: CanvasEnv, url: string): Promise<string> {
  const where = `origin=${env.location?.origin ?? '?'} href=${env.location?.href ?? '?'}`;
  if (typeof env.fetch !== 'function') return ` [${where} fetch=unavailable]`;
  try {
    const response = await env.fetch(url, { cache: 'no-store' });
    const type = response.headers?.get?.('content-type') ?? '?';
    return ` [${where} fetch=${response.status} ${type}]`;
  } catch (error) {
    return ` [${where} fetch-threw=${String(error)}]`;
  }
}

/**
 * Inject one `<script type="module">` and resolve once its module graph has run.
 *
 * `type="module"` is what the bootstrap is; the `load` event fires after the
 * bootstrap's top-level code has executed (so the global it publishes is there,
 * though its wasm may still be initialising behind `ready`). A fetch, parse or
 * evaluation failure fires `error`.
 */
function injectModuleScript(env: CanvasEnv, url: string): Promise<HTMLScriptElement> {
  return new Promise((resolve, reject) => {
    const doc = env.document;
    if (!doc || typeof doc.createElement !== 'function') {
      reject(new Error(`script ${url} failed: no document`));
      return;
    }
    const script = doc.createElement('script');
    script.type = 'module';
    script.src = url;
    // Dynamically created scripts default to `async`; insertion order does not
    // matter for a single tag, but a deterministic load does.
    script.async = false;
    script.addEventListener('load', () => resolve(script));
    script.addEventListener('error', () => {
      script.remove?.();
      reject(new Error(`script ${url} failed: error event`));
    });
    const parent = doc.head ?? doc.body ?? doc.documentElement;
    parent.appendChild(script);
  });
}

/**
 * Load the wasm session bootstrap once per environment.
 *
 * One `<script>` tag, one wasm fetch, one init: the promise is cached per `env`
 * (the page's global), so a second caller - a remount, a second effect run - waits
 * on the first attempt instead of appending a second tag.
 */
const bootstrapByEnv = new WeakMap<object, Promise<CanvasModule>>();

/**
 * Load the bootstrap module, await the session's init, and check the exports.
 *
 * `target` is the served directory, or the bootstrap URL [`canvasModuleUrl`]
 * returns. The bootstrap itself names the wasm binary (`app_web_bg.wasm` next to
 * it) and publishes `{ ready, ...module }`; `ready` is awaited so an init
 * rejection is reported here instead of surfacing later as a random export throw.
 *
 * Failures name the URL and the failing step (`script … failed` when the tag
 * cannot load, `init … failed` when the wasm cannot be instantiated) and carry the
 * origin/fetch probe, so the host's refusal line is actionable.
 */
export function loadCanvasModule(target: unknown = CANVAS_BASE, env: CanvasEnv = globalThis): Promise<CanvasModule> {
  let pending = bootstrapByEnv.get(env);
  if (pending === undefined) {
    // Single-flight while in flight, but a **failed** bootstrap is not cached: a
    // transient script fetch or wasm instantiation error on a cold load would
    // otherwise poison every later caller for the life of the page (the shell
    // vocabulary then never loads and every command reports "not supported").
    // The next caller simply starts a fresh attempt.
    pending = bootstrap(env, target).catch(error => {
      bootstrapByEnv.delete(env);
      throw error;
    });
    bootstrapByEnv.set(env, pending);
  }
  return pending;
}

async function bootstrap(env: CanvasEnv, target: unknown): Promise<CanvasModule> {
  const script = canvasScriptUrl(target);
  const wasm = canvasWasmUrl(target);
  try {
    await injectModuleScript(env, script);
  } catch (error) {
    const probe = await assetProbe(env, script);
    throw new Error(`${(error as Error).message}${probe}`, { cause: error });
  }
  const loaded = env[CANVAS_GLOBAL];
  if (!loaded || typeof loaded !== 'object') {
    const probe = await assetProbe(env, script);
    throw new Error(`script ${script} failed: no ${CANVAS_GLOBAL} after load${probe}`);
  }
  const module = loaded as Record<string, unknown>;
  if (module.ready === undefined) {
    const probe = await assetProbe(env, script);
    throw new Error(`script ${script} failed: ${CANVAS_GLOBAL}.ready is missing${probe}`);
  }
  try {
    await module.ready;
  } catch (error) {
    const failure = (error ?? {}) as { readonly name?: unknown; readonly message?: unknown };
    const name = typeof failure.name === 'string' && failure.name ? failure.name : 'Error';
    const message = typeof failure.message === 'string' && failure.message ? failure.message : String(error);
    const probe = await assetProbe(env, wasm);
    throw new Error(`init ${wasm} failed: ${name}: ${message}${probe}`, { cause: error });
  }
  // The bootstrap spreads the wasm-bindgen module namespace next to `ready`, so the
  // transport's `module.start(...)` contract is met by this object. A half-working
  // artifact is rejected here instead of failing later on a random call.
  for (const name of CANVAS_EXPORTS) {
    if (typeof module[name] !== 'function') {
      throw new Error(`canvas module ${script}: missing export ${name}`);
    }
  }
  // Every export this transport calls was just checked to be a function; the rest
  // of the namespace is forwarded untouched.
  return loaded as CanvasModule;
}

/**
 * The CSS size and DPR the session is configured with, from a partition rect.
 *
 * Mirrors the reference shell: a zero-sized element is reported as `1` CSS px
 * (a surface cannot be zero), and an absent/non-finite/non-positive
 * `devicePixelRatio` falls back to `1` instead of poisoning the physical size.
 *
 * A rect that does not exist or has a non-finite axis yields `null`: "no size" is
 * not a size, and the transport must then make no call at all rather than invent
 * a placeholder.
 */
export function canvasCssSize(rect: unknown): CanvasCssSize | null {
  if (!rect) return null;
  const source = rect as { readonly width?: unknown; readonly height?: unknown; readonly dpr?: unknown };
  const { width, height } = source;
  if (typeof width !== 'number' || !Number.isFinite(width)) return null;
  if (typeof height !== 'number' || !Number.isFinite(height)) return null;
  const reported = source.dpr;
  const dpr = typeof reported === 'number' && Number.isFinite(reported) && reported > 0 ? reported : 1;
  return { width: Math.max(width, 1), height: Math.max(height, 1), dpr };
}

/** Parse one JSON status string; `null` when it is not an object. */
export function parseCanvasStatus(json: unknown): Record<string, unknown> | null {
  if (typeof json !== 'string') return null;
  try {
    const parsed: unknown = JSON.parse(json);
    return parsed !== null && typeof parsed === 'object' && !Array.isArray(parsed)
      ? parsed as Record<string, unknown>
      : null;
  } catch {
    return null;
  }
}

/**
 * The failure carried by one status string, or `null` for a success.
 *
 * Shape: `{ step, detail, marker }`. `detail` is always something the session
 * itself reported (its `error`) or the raw status text - this module never
 * fabricates user-facing copy, so the host owns every word of the diagnosis.
 * `marker` is passed through untouched (`webgl2` carries
 * `yacr: unsupported-runtime: webgl2`); it is `null` when the status has none.
 */
export function statusFailure(parsed: Record<string, unknown> | null, raw: unknown = ''): CanvasFailure | null {
  if (parsed === null) {
    return { step: CANVAS_STEP_UNREADABLE, detail: String(raw), marker: null };
  }
  if (parsed.ok === true) return null;
  return {
    step: typeof parsed.step === 'string' && parsed.step.length > 0 ? parsed.step : CANVAS_STEP_UNCLASSIFIED,
    detail: typeof parsed.error === 'string' ? parsed.error : String(raw),
    marker: typeof parsed.marker === 'string' && parsed.marker.length > 0 ? parsed.marker : null,
  };
}

/** What a caller may hand [`createCanvasTransport`]. */
export interface CanvasTransportOptions {
  /** The loaded (and already validated) session module. */
  module?: CanvasModule;
  /** The `.native-input` element this transport belongs to (identity only). */
  element?: Element | null;
  /** The partition rect to start from. */
  rect?: unknown;
  /** Called with the session's own status for every successful call. */
  onStatus?: (status: Record<string, unknown> | null) => void;
  /** Called **once**, with the first failure. */
  onFailure?: (failure: CanvasFailure) => void;
  /** The id of the canvas the session presents on. */
  canvasId?: string;
}

/** The transport `App.tsx` drives from the partition rect. */
export interface CanvasTransport {
  /** The `.native-input` element this transport belongs to (never the canvas). */
  readonly element: Element | null;
  /** Feed a new partition rect; starts once, resizes on a real size change. */
  update(rect: unknown): boolean;
  /** Resolves when every queued call has settled (diagnostics and tests). */
  whenIdle(): Promise<void>;
  /** Whether a failure latched the transport shut. */
  readonly failed: boolean;
  dispose(): void;
}

/**
 * The canvas session's call surface, bound to one partition rect.
 *
 * One `start(...)` per transport (`start` refuses a second call: one canvas has
 * exactly one presenter), then `resize(...)` only when the *size* really changed
 * (`width|height|dpr`; a move within the same viewport is not a resize). Calls are
 * serialised on a promise chain, so a resize that arrives while `start` is still
 * resolving runs after it and never concurrently.
 *
 * Failure policy: the first failure - a rejected export, an unreadable status, or
 * `ok: false` - is reported once through `onFailure({ step, detail, marker })`,
 * latches the transport shut, and every later call is dropped. No retry, no
 * backoff loop, no silent success: a dead session is reported once, not spammed.
 *
 * `element` is the `.native-input` element this transport was created for; it is
 * kept for identity/diagnostics only. The transport attaches **no** listener to it
 * and never touches the `<canvas>`.
 */
export function createCanvasTransport({
  module,
  element = null,
  rect,
  onStatus = () => {},
  onFailure = () => {},
  canvasId = CANVAS_ID,
}: CanvasTransportOptions = {}): CanvasTransport {
  if (!module || typeof module.start !== 'function') {
    throw new TypeError('createCanvasTransport: module.start is required');
  }
  let chain: Promise<void> = Promise.resolve();
  let disposed = false;
  let failed = false;
  let started = false;
  let lastSize = '';

  const report = (raw: unknown): void => {
    const parsed = parseCanvasStatus(raw);
    const failure = statusFailure(parsed, raw);
    if (failure) {
      failed = true;
      onFailure(failure);
      return;
    }
    onStatus(parsed);
  };

  // One serialised step. The guard runs twice on purpose: once now (so a disposed
  // transport enqueues nothing) and once when its turn comes (so work queued
  // before a failure never reaches a dead session).
  const call = (name: string, perform: () => unknown): void => {
    if (disposed || failed) return;
    chain = chain
      .then(async () => {
        if (disposed || failed) return;
        let raw: unknown;
        try {
          raw = await perform();
        } catch (error) {
          failed = true;
          onFailure({ step: CANVAS_STEP_CALL, detail: String(error), marker: null, at: name });
          return;
        }
        report(raw);
      })
      .catch(error => {
        failed = true;
        onFailure({ step: CANVAS_STEP_CALL, detail: String(error), marker: null, at: name });
      });
  };

  const sizeKey = (size: CanvasCssSize): string => `${size.width}|${size.height}|${size.dpr}`;

  const update = (nextRect: unknown): boolean => {
    if (disposed || failed) return false;
    const size = canvasCssSize(nextRect);
    if (size === null) return false;
    if (!started) {
      started = true;
      lastSize = sizeKey(size);
      call('start', () => module.start(canvasId, size.width, size.height, size.dpr));
      return true;
    }
    const key = sizeKey(size);
    if (key === lastSize) return false;
    lastSize = key;
    call('resize', () => module.resize(size.width, size.height, size.dpr));
    return true;
  };

  update(rect);

  return {
    element,
    /** Feed a new partition rect; starts once, resizes on a real size change. */
    update,
    /** Resolves when every queued call has settled (diagnostics and tests). */
    whenIdle(): Promise<void> {
      return chain;
    },
    /** Whether a failure latched the transport shut. */
    get failed(): boolean {
      return failed;
    },
    dispose(): void {
      disposed = true;
    },
  };
}

/** The window surface [`watchCanvasRect`] needs (structural, like `ProbeEnv`). */
export interface RectWatchEnv {
  readonly devicePixelRatio?: number;
  readonly ResizeObserver: typeof ResizeObserver;
  requestAnimationFrame(callback: FrameRequestCallback): number;
  cancelAnimationFrame(handle: number): void;
  matchMedia(query: string): MediaQueryList;
  addEventListener(type: string, listener: EventListener): void;
  removeEventListener(type: string, listener: EventListener): void;
}

/**
 * Re-measure the partition and hand every change to `onChange`.
 *
 * A `dom-canvas` host has no IPC `resize` report to piggy-back on, so the same
 * triggers the IPC binding watches are watched here: the element itself, every
 * chrome region that can move or shrink it (window resize, ribbon, palette dock,
 * history expand), window resize and a DPR change. Measurement is coalesced to one
 * animation frame; the initial rect is reported synchronously.
 *
 * Returns the unbind function.
 */
export function watchCanvasRect(
  element: Element | null | undefined,
  onChange: (rect: ReturnType<typeof rectFromElement>) => void,
  env: RectWatchEnv = globalThis,
): () => void {
  if (!element || typeof onChange !== 'function') {
    throw new TypeError('watchCanvasRect: element and onChange are required');
  }
  const dpr = (): number => {
    const ratio = env.devicePixelRatio;
    return typeof ratio === 'number' && Number.isFinite(ratio) && ratio > 0 ? ratio : 1;
  };
  const measure = (): void => onChange(rectFromElement(element, dpr()));
  let frame: number | null = null;
  const schedule = (): void => {
    if (frame !== null) return;
    frame = env.requestAnimationFrame(() => {
      frame = null;
      measure();
    });
  };
  let media: MediaQueryList | null = null;
  const watchDpr = (): void => {
    media?.removeEventListener('change', onDpr);
    const query = env.matchMedia(`(resolution: ${dpr()}dppx)`);
    media = query;
    query.addEventListener('change', onDpr);
  };
  function onDpr(): void {
    schedule();
    watchDpr();
  }
  const observer = new env.ResizeObserver(schedule);
  observer.observe(element);
  const layoutRoot = element.closest?.('.shell') ?? element.parentElement;
  for (const region of layoutRoot?.querySelectorAll('.app-region') ?? []) observer.observe(region);
  env.addEventListener('resize', schedule);
  watchDpr();
  measure();
  return () => {
    if (frame !== null) env.cancelAnimationFrame(frame);
    frame = null;
    observer.disconnect();
    media?.removeEventListener('change', onDpr);
    env.removeEventListener('resize', schedule);
  };
}
