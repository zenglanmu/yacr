impl ExtendedCommandId {
    /// Whether the command needs Work mode.
    ///
    /// Session-only commands, read-only reports and named refusals are
    /// Viewer-legal; every command that writes the drawing (`MVIEW`, the typed
    /// `PAGESETUP`/`PSETUPIN` forms and the existing edits) declares itself here.
    pub fn requires_work_mode(self) -> bool {
        matches!(
            self,
            Self::CenterMark
                | Self::CenterLine
                | Self::NCopy
                | Self::CopyToLayer
                | Self::DashCopyToLayer
                | Self::CDOrder
                | Self::Flatten
                | Self::XPlode
                | Self::BTrim
                | Self::BExtend
                | Self::Change
                | Self::ChProp
                | Self::Array
                | Self::DashArray
                | Self::ArrayClassic
                | Self::Blend
                | Self::BreakLine
                | Self::DashBlock
                | Self::DashBoundary
                | Self::DashInsert
                | Self::DashHatch
                | Self::DashHatchEdit
                | Self::ExOffset
                | Self::LayerStateSave
                | Self::MView
                | Self::PageSetup
                | Self::DashPageSetup
                | Self::PageSetupIn
                | Self::DashPageSetupIn
                // Wave 16 raster-image authoring writes one entity row (attach)
                // or rewrites one selected image's clip or display transfer.
                | Self::ImageAttach
                | Self::ImageClip
                | Self::ImageAdjust
                | Self::DashImageAdjust
                // TABLE / -TABLE insert one table row; TABLEDIT rewrites one
                // selected table's cell text.
                | Self::TableCreate
                | Self::DashTable
                | Self::TableEdit
                // Wave 26 annotation writes: TXTEXP inserts outline polylines and
                // deletes the text sources; ARCTEXT inserts per-character TEXT rows
                // and consumes the selected text entities.
                | Self::TextExplode
                | Self::ArcText
                // Wave 26 paper-space writes: per-viewport layer overrides, viewport
                // grids, paper-relative block/text scaling.
                | Self::MvSetup
                | Self::PsbScale
                | Self::PstScale
                // Wave 26 viewport alignment writes one layout patch each.
                | Self::AlignSpace
                | Self::VpSync
        )
    }
}
