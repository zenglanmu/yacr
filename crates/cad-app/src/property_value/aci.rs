/// The sRGB triple of an ACI index, or `None` for `0` (ByBlock) and `256`
/// (ByLayer), which are symbolic rather than colours.
pub(crate) fn rgb_for_aci(index: u16) -> Option<[u8; 3]> {
    match index {
        0 | 256 => None,
        index => ACI_COLORS
            .get(usize::from(index))
            .map(|(r, g, b)| [*r, *g, *b]),
    }
}

/// The canonical (lowest) ACI index whose sRGB triple is exactly `rgb`, if any.
///
/// Index `0` is excluded: it is the ByBlock placeholder, never a colour match.
pub(crate) fn aci_for_rgb(rgb: [u8; 3]) -> Option<u16> {
    (1..=255u16).find(|index| rgb_for_aci(*index) == Some(rgb))
}
