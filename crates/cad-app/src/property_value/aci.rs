//! is a real colour, so [`rgb_for_aci`] rejects them and callers map them to the
//! symbolic [`cad_db::EntityColor`] variants instead. Index `7` is white (the
//! nominal dark-background default), exactly as the source table documents.
//!
//! The table is factual palette data: it is the standard AutoCAD mapping (hue
//! steps of 15 degrees in groups of ten: a full colour and its pastel at 1, 0.8,
//! 0.6, 0.5 and 0.3 intensity, rounded down). Some true colours repeat across
//! indices (`1`/`10`, `2`/`50`, ...); [`aci_for_rgb`] therefore returns the
//! **lowest** matching index, which is the canonical one.

